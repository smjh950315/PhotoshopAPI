namespace Photoshop.NET;

/// <summary>Pixel sample depth used by a Photoshop document or layer.</summary>
public enum PhotoshopBitDepth
{
    /// <summary>Unsigned 8-bit samples.</summary>
    Bit8 = 8,
    /// <summary>Unsigned 16-bit samples.</summary>
    Bit16 = 16,
    /// <summary>32-bit floating-point samples.</summary>
    Bit32 = 32
}
